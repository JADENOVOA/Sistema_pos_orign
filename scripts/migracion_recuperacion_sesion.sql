-- Ejecutar UNA VEZ en la base BODEGA_LAPERUANITA con una cuenta administradora.
-- La columna email queda opcional para conservar los usuarios actuales. Los correos
-- deben ser validados y completados por un administrador antes de usar recuperación.
BEGIN;

ALTER TABLE public.usuarios ADD COLUMN IF NOT EXISTS email VARCHAR(254);
ALTER TABLE public.usuarios ADD COLUMN IF NOT EXISTS email_verificado BOOLEAN NOT NULL DEFAULT FALSE;

DO $$
BEGIN
    IF EXISTS (
        SELECT lower(btrim(email))
        FROM public.usuarios
        WHERE email IS NOT NULL AND btrim(email) <> ''
        GROUP BY lower(btrim(email))
        HAVING count(*) > 1
    ) THEN
        RAISE EXCEPTION 'Hay correos duplicados en usuarios. Corríjalos antes de crear el índice único.';
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS ux_usuarios_email_lower
    ON public.usuarios (lower(btrim(email)))
    WHERE email IS NOT NULL AND btrim(email) <> '';

CREATE TABLE IF NOT EXISTS public.recuperacion_password (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL REFERENCES public.usuarios(id_usuario),
    token_hash CHAR(64) NOT NULL UNIQUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    expira_en TIMESTAMPTZ NOT NULL,
    usado_en TIMESTAMPTZ NULL,
    intentos SMALLINT NOT NULL DEFAULT 0 CHECK (intentos >= 0 AND intentos <= 5)
);
CREATE INDEX IF NOT EXISTS ix_recuperacion_usuario_fecha
    ON public.recuperacion_password (id_usuario, creado_en DESC);

CREATE TABLE IF NOT EXISTS public.sesiones_recordadas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL REFERENCES public.usuarios(id_usuario),
    token_hash CHAR(64) NOT NULL UNIQUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    expira_en TIMESTAMPTZ NOT NULL,
    revocado_en TIMESTAMPTZ NULL
);
CREATE INDEX IF NOT EXISTS ix_sesiones_usuario_activa
    ON public.sesiones_recordadas (id_usuario, expira_en)
    WHERE revocado_en IS NULL;

-- Si existe el rol recomendado, concede permisos de aplicación sin privilegios DDL.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'pos_app') THEN
        EXECUTE 'GRANT SELECT, INSERT, UPDATE ON public.recuperacion_password, public.sesiones_recordadas TO pos_app';
        EXECUTE 'GRANT USAGE, SELECT, UPDATE ON SEQUENCE public.recuperacion_password_id_seq, public.sesiones_recordadas_id_seq TO pos_app';
    END IF;
END $$;

COMMIT;
